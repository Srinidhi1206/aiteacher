export function getLessonPlan(subjectSlug: string, topicSlug: string): LessonPlan | null {
  const found = getTopicContent(subjectSlug, topicSlug);
  if (!found) return null;
  const { topic, chapter, content } = found;
  const questions = authoredLessons[topic.id] ?? genericQuestions(topic.id, topic.name, chapter.name);
  return {
    topicId: topic.id,
    recap: content.summary,
    examples: content.examples,
    questions,
  };
}

