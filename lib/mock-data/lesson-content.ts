// fill-blank uses a forgiving case-insensitive substring match; short-answer
// checks for a meaningful keyword overlap so the demo never feels broken.
export function isLessonAnswerCorrect(question: LessonQuestion, studentAnswer: string): boolean {
  const answer = studentAnswer.trim().toLowerCase();
  if (!answer) return false;
  const correct = question.correctAnswer.trim().toLowerCase();

  if (question.type === "mcq" || question.type === "true-false") {
    return answer === correct;
  }

  if (question.type === "fill-blank") {
    const normalize = (s: string) => s.replace(/[{}()\s]/g, "");
    return normalize(answer).includes(normalize(correct)) || normalize(correct).includes(normalize(answer));
  }

  // short-answer: lenient keyword-based check
  const keywords = correct
    .replace(/[^a-z0-9.\s]/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 2);
  if (keywords.length === 0) return answer.length > 10;
  const hits = keywords.filter((k) => answer.includes(k)).length;
  return hits > 0 || answer.length > 25;
}
